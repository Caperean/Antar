use wasm_bindgen::prelude::*;

/// Opaque CPU-side texture identifier.  GPU textures live in `GpuContext`.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub struct TextureHandle(pub u32);

/// Axis-aligned rectangle in screen-space pixels.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct Rect {
    pub x: f32,
    pub y: f32,
    pub w: f32,
    pub h: f32,
}

impl Rect {
    pub fn new(x: f32, y: f32, w: f32, h: f32) -> Self {
        Self { x, y, w, h }
    }

    pub fn from_js(obj: &JsValue) -> Result<Self, JsValue> {
        Ok(Self::new(
            finite_f32_field(obj, "x")?,
            finite_f32_field(obj, "y")?,
            finite_f32_field(obj, "w")?,
            finite_f32_field(obj, "h")?,
        ))
    }
}

/// RGBA color with components in [0.0, 1.0].
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct Color {
    pub r: f32,
    pub g: f32,
    pub b: f32,
    pub a: f32,
}

impl Color {
    pub const WHITE: Self = Self { r: 1.0, g: 1.0, b: 1.0, a: 1.0 };
    pub const BLACK: Self = Self { r: 0.0, g: 0.0, b: 0.0, a: 1.0 };
    pub const TRANSPARENT: Self = Self { r: 0.0, g: 0.0, b: 0.0, a: 0.0 };

    pub fn new(r: f32, g: f32, b: f32, a: f32) -> Self {
        Self { r, g, b, a }
    }

    /// Parse a CSS color string (currently hex: `"#rrggbb"` or `"#rrggbbaa"`).
    pub fn from_css(css: &str) -> Option<Self> {
        Self::from_hex(css)
    }

    pub fn from_js(obj: &JsValue) -> Result<Self, JsValue> {
        Ok(Self::new(
            finite_f32_field(obj, "r")?,
            finite_f32_field(obj, "g")?,
            finite_f32_field(obj, "b")?,
            finite_f32_field(obj, "a").unwrap_or(1.0),
        ))
    }

    /// Parse a CSS hex color string: `"#rrggbb"` or `"#rrggbbaa"`.
    pub fn from_hex(hex: &str) -> Option<Self> {
        let hex = hex.trim_start_matches('#');
        let parse = |s: &str| u8::from_str_radix(s, 16).ok();
        match hex.len() {
            6 => Some(Self {
                r: parse(&hex[0..2])? as f32 / 255.0,
                g: parse(&hex[2..4])? as f32 / 255.0,
                b: parse(&hex[4..6])? as f32 / 255.0,
                a: 1.0,
            }),
            8 => Some(Self {
                r: parse(&hex[0..2])? as f32 / 255.0,
                g: parse(&hex[2..4])? as f32 / 255.0,
                b: parse(&hex[4..6])? as f32 / 255.0,
                a: parse(&hex[6..8])? as f32 / 255.0,
            }),
            _ => None,
        }
    }
}

/// Column-major 3×3 affine transform (operates on 2-D homogeneous coords).
/// Stored as the six non-trivial components: [a, b, c, d, tx, ty].
///
/// ```
/// | a  c  tx |
/// | b  d  ty |
/// | 0  0   1 |
/// ```
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct Transform {
    pub a: f32,
    pub b: f32,
    pub c: f32,
    pub d: f32,
    pub tx: f32,
    pub ty: f32,
}

/// GPU-ready sprite instance generated by `Renderer2D`.
/// `src` is in texture pixel coordinates; `GpuContext` converts to UVs.
#[derive(Clone, Copy, Debug)]
pub struct SpriteInstance {
    pub texture_id: u32,
    pub dst: Rect,
    pub src: Rect,
    pub transform: Transform,
    pub color: Color,
    pub alpha: f32,
}

/// GPU-ready solid-rect instance generated by `Renderer2D`.
#[derive(Clone, Copy, Debug)]
pub struct RectInstance {
    pub rect: Rect,
    pub color: Color,
    pub transform: Transform,
    pub alpha: f32,
}

/// Polygon rendering mode (matching shader constants).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum PolygonRenderMode {
    Fill = 0,
    Outline = 1,
    Mask = 2,
}

/// GPU-ready polygon instance metadata (matches shader PolygonMeta).
#[derive(Clone, Debug)]
pub struct PolygonMeta {
    pub vertex_offset: u32,
    pub vertex_count: u32,
    pub translate: [f32; 2],
    pub scale: [f32; 2],
    pub rotation: f32,
    pub render_mode: PolygonRenderMode,
    pub bbox_min: [f32; 2],
    pub bbox_max: [f32; 2],
    pub outline_width: f32,
    pub flags: u32,
    pub tint_color: Color,
}

/// CPU-side polygon instance with pre-transformed vertices.
/// Vertices are transformed on CPU before upload (per design in zalozenia.txt).
#[derive(Clone, Debug)]
pub struct PolygonInstance {
    pub meta: PolygonMeta,
    pub vertices: Vec<[f32; 2]>, // Already transformed to screen space
    pub texture_id: Option<TextureHandle>,
}

impl Transform {
    pub const IDENTITY: Self = Self { a: 1.0, b: 0.0, c: 0.0, d: 1.0, tx: 0.0, ty: 0.0 };

    /// Concatenate (multiply) two transforms: self ∘ other.
    #[inline]
    pub fn concat(&self, o: &Self) -> Self {
        Self {
            a:  self.a * o.a  + self.c * o.b,
            b:  self.b * o.a  + self.d * o.b,
            c:  self.a * o.c  + self.c * o.d,
            d:  self.b * o.c  + self.d * o.d,
            tx: self.a * o.tx + self.c * o.ty + self.tx,
            ty: self.b * o.tx + self.d * o.ty + self.ty,
        }
    }

    pub fn translate(tx: f32, ty: f32) -> Self {
        Self { a: 1.0, b: 0.0, c: 0.0, d: 1.0, tx, ty }
    }

    pub fn rotate(radians: f32) -> Self {
        let (s, c) = radians.sin_cos();
        Self { a: c, b: s, c: -s, d: c, tx: 0.0, ty: 0.0 }
    }

    pub fn scale(sx: f32, sy: f32) -> Self {
        Self { a: sx, b: 0.0, c: 0.0, d: sy, tx: 0.0, ty: 0.0 }
    }

    /// Convert to a flat [f32; 9] array for upload to a uniform buffer.
    pub fn to_mat3_array(&self) -> [f32; 9] {
        [
            self.a,  self.b,  0.0,
            self.c,  self.d,  0.0,
            self.tx, self.ty, 1.0,
        ]
    }
}

fn f64_field(obj: &JsValue, key: &str) -> Result<f64, JsValue> {
    js_sys::Reflect::get(obj, &key.into())?
        .as_f64()
        .ok_or_else(|| JsValue::from_str(&format!("invalid field: {key}")))
}

/// Reject NaN / Infinity coming from JavaScript before they reach transforms.
pub(crate) fn finite_f32(value: f64, field: &str) -> Result<f32, JsValue> {
    if !value.is_finite() {
        return Err(JsValue::from_str(&format!(
            "field '{field}' must be a finite number"
        )));
    }
    Ok(value as f32)
}

pub(crate) fn finite_f32_from_f32(value: f32, field: &str) -> Result<f32, JsValue> {
    if !value.is_finite() {
        return Err(JsValue::from_str(&format!(
            "field '{field}' must be a finite number"
        )));
    }
    Ok(value)
}

pub(crate) fn finite_f32_field(obj: &JsValue, key: &str) -> Result<f32, JsValue> {
    finite_f32(f64_field(obj, key)?, key)
}
